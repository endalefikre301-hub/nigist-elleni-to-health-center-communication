import pandas as pd
from datetime import datetime

# Initialize mock databases for health centers, referrals, and feedback
health_centers = [
    {"center_id": "HC001", "name": "North Valley Clinic", "distance_km": 15},
    {"center_id": "HC002", "name": "East Riverside Health Post", "distance_km": 28},
    {"center_id": "HC003", "name": "South Hills Community Center", "distance_km": 42}
]

referrals_db = []
feedbacks_db = []

class DigitalHealthSupervisor:
    def __init__(self, hospital_name):
        self.hospital_name = hospital_name
        self.centers = {hc["center_id"]: hc["name"] for hc in health_centers}

    def send_referral(self, patient_name, from_center_id, urgency, clinical_notes):
        """Allows a remote center to digitally refer a patient to the supervising hospital"""
        if from_center_id not in self.centers:
            return "Error: Invalid Health Center ID"

        referral_id = f"REF-{len(referrals_db) + 101}"
        referral = {
            "referral_id": referral_id,
            "patient_name": patient_name,
            "from_center": self.centers[from_center_id],
            "to_hospital": self.hospital_name,
            "urgency": urgency,
            "clinical_notes": clinical_notes,
            "status": "Pending Review",
            "timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        }
        referrals_db.append(referral)
        return f"Referral {referral_id} successfully submitted digitally."

    def send_feedback(self, referral_id, supervision_feedback, actionable_steps):
        """Allows the supervising hospital to send clinical feedback back to the remote center"""
        referral = next((r for r in referrals_db if r["referral_id"] == referral_id), None)
        if not referral:
            return f"Error: Referral {referral_id} not found."

        referral["status"] = "Feedback Sent"

        feedback = {
            "feedback_id": f"FB-{len(feedbacks_db) + 501}",
            "referral_id": referral_id,
            "patient_name": referral["patient_name"],
            "target_center": referral["from_center"],
            "feedback_text": supervision_feedback,
            "actionable_steps": actionable_steps,
            "timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        }
        feedbacks_db.append(feedback)
        return f"Feedback sent successfully to {referral['from_center']}."

    def view_referral_dashboard(self):
        """Displays all referrals in a clean dashboard"""
        if not referrals_db:
            return "No digital referrals on record."
        return pd.DataFrame(referrals_db)

    def view_feedback_dashboard(self):
        """Displays all outgoing feedback logs"""
        if not feedbacks_db:
            return "No digital feedback logs on record."
        return pd.DataFrame(feedbacks_db)

# --- System Demonstration ---
# Initialize the digital supervision system for 'Central General Hospital'
supervisor = DigitalHealthSupervisor("Central General Hospital")

# 1. Simulate remote clinics sending referrals to the hospital
print("=== 1. Receiving Incoming Digital Referrals ===")
print(supervisor.send_referral("Alice Smith", "HC001", "High", "Severe asthma exacerbation, requiring specialized ventilation."))
print(supervisor.send_referral("Bob Jones", "HC003", "Medium", "Uncontrolled type 2 diabetes, requests therapy adjustment consultation."))
print()

# View Dashboard of Incoming Referrals
print("=== Current Referral Dashboard ===")
display(supervisor.view_referral_dashboard())
print()

# 2. Supervising hospital sends feedback/clinical guidance back to the centers
print("=== 2. Sending Supervision Clinical Feedback ===")
print(supervisor.send_feedback(
    referral_id="REF-101",
    supervision_feedback="Patient admitted successfully. Administered IV Magnesium Sulfate. Ensure your clinic stocks standard emergency bronchodilators.",
    actionable_steps="Verify medication inventory weekly; send staff to next month's asthma management seminar."
))
print()

# View Feedback Log Dashboard
print("=== Digital Feedback Logs ===")
display(supervisor.view_feedback_dashboard())

